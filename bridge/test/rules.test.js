'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const { normalizeCommand, giftPoints, shouldCountGift, sanitizedUsername } = require('../src/rules');
const gifts = require('../config/gifts.json');
test('Rouge via commentaire', () => assert.deepEqual(normalizeCommand(' !join RED '), {command:'join',team:'red'}));
test('Bleu via commentaire', () => assert.equal(normalizeCommand('!join blue').team,'blue'));
test('Attaque gratuite', () => assert.equal(normalizeCommand('!attack').command,'attack'));
test('Interdiction des commandes arbitraires', () => assert.equal(normalizeCommand('!erase all'), null));
test('Rose = 1 ame de jeu', () => assert.equal(giftPoints('Rose',gifts,1),1));
test('Rose x3 = 3 ames', () => assert.equal(giftPoints('Rose',gifts,3),3));
test('Finger Heart = 6 ames', () => assert.equal(giftPoints('Finger Heart',gifts,1),6));
test('Doughnut = 35 ames', () => assert.equal(giftPoints('Doughnut',gifts,1),35));
test('Galaxy = 150 ames', () => assert.equal(giftPoints('Galaxy',gifts,1),150));
test('Cadeau inconnu = aucune ame', () => assert.equal(giftPoints('Unknown',gifts),0));
test('Series TikTok inachevees ignorees', () => assert.equal(shouldCountGift({giftDetails:{giftType:1},repeatEnd:false}),false));
test('Series TikTok finies valides', () => assert.equal(shouldCountGift({giftDetails:{giftType:1},repeatEnd:true}),true));
test('Cadeau hors serie valide', () => assert.equal(shouldCountGift({giftType:0,repeatEnd:false}),true));
test('Pseudonyme sans retour ligne', () => assert.equal(sanitizedUsername('alpha\nbeta'),'alphabeta'));
