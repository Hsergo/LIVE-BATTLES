'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const rules=require('../rules');
const gifts=require('../gifts.json');
test('Rejoindre gratuitement',()=>assert.equal(rules.commandOf('!join'),'!join'));
test('Construire en francais',()=>assert.equal(rules.commandOf('!construire'),'!build'));
test('Reparer en francais',()=>assert.equal(rules.commandOf('!réparer'),'!repair'));
test('Sauver en francais',()=>assert.equal(rules.commandOf('!sauver'),'!rescue'));
test('Vote 1 2 ou 3',()=>assert.equal(rules.commandOf(' !vote   2 '),'2'));
test('Commande arbitraire refusee',()=>assert.equal(rules.commandOf('!admin grant'),null));
test('Pseudo assaini',()=>assert.equal(rules.userOf('AAA\nBBB'),'AAABBB'));
test('Rose donne 4 ressources fictives',()=>assert.equal(rules.giftMaterials('Rose',gifts,1),4));
test('Doughnut x3 donne 120',()=>assert.equal(rules.giftMaterials('Doughnut',gifts,3),120));
test('Galaxy donne 120',()=>assert.equal(rules.giftMaterials('Galaxy',gifts,1),120));
test('Cadeau inconnu pas de ressource',()=>assert.equal(rules.giftMaterials('JeNeConnaisPas',gifts,1),0));
test('Combo encore en cours ignore',()=>assert.equal(rules.giftCompleted({giftDetails:{giftType:1},repeatEnd:false}),false));
test('Combo termine accepte',()=>assert.equal(rules.giftCompleted({giftDetails:{giftType:1},repeatEnd:true}),true));
test('Autre cadeau accepte',()=>assert.equal(rules.giftCompleted({giftType:0}),true));

test('Les regles s affichent a la demande',()=>assert.equal(rules.commandOf('!regles'),'!rules'));
test('Les actions speciales sont gratuites',()=>assert.equal(rules.commandOf('!pump'),'!special'));
test('La commande !signal existe pour le phare',()=>assert.equal(rules.commandOf('!signal'),'!special'));
test('La commande !valve existe pour le barrage',()=>assert.equal(rules.commandOf('!valve'),'!special'));
test('La commande !launch existe pour l heliport',()=>assert.equal(rules.commandOf('!launch'),'!special'));
